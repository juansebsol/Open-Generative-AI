#!/usr/bin/env node
// Bundles the provider catalog JSON into plain ES modules so the same files
// load in Next.js and in plain Node scripts:
//   packages/studio/src/providers/catalog/routes.generated.js   (client + server)
//   packages/studio/src/providers/catalog/schemas.generated.js  (server only)
// Run after adding or removing a route group. sync-provider-schemas.mjs calls it too.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CATALOG_DIR = path.join(ROOT, 'packages/studio/src/providers/catalog');

const HEADER = '// Generated by scripts/build-catalog-index.mjs. Do not edit by hand.\n';

export function buildCatalogIndex() {
  const routeFiles = fs.readdirSync(path.join(CATALOG_DIR, 'routes')).filter((file) => file.endsWith('.json')).sort();
  const groups = Object.fromEntries(routeFiles.map((file) => [
    path.basename(file, '.json'),
    JSON.parse(fs.readFileSync(path.join(CATALOG_DIR, 'routes', file), 'utf8')),
  ]));
  fs.writeFileSync(
    path.join(CATALOG_DIR, 'routes.generated.js'),
    `${HEADER}// Source: catalog/routes/*.json\n\nexport const ROUTE_GROUPS = ${JSON.stringify(groups, null, 1)};\n`,
  );

  const schemaDir = path.join(CATALOG_DIR, 'schemas');
  fs.mkdirSync(schemaDir, { recursive: true });
  const schemaFiles = fs.readdirSync(schemaDir).filter((file) => file.endsWith('.json')).sort();
  const byProvider = {};
  for (const file of schemaFiles) {
    const provider = file.split('.').slice(-2, -1)[0];
    Object.assign((byProvider[provider] ||= {}), JSON.parse(fs.readFileSync(path.join(schemaDir, file), 'utf8')));
  }
  fs.writeFileSync(
    path.join(CATALOG_DIR, 'schemas.generated.js'),
    `${HEADER}// Source: catalog/schemas/*.json (server-side only)\n\nexport const SCHEMAS = ${JSON.stringify(byProvider)};\n`,
  );
  return { routeFiles, schemaFiles };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { routeFiles, schemaFiles } = buildCatalogIndex();
  console.log(`catalog index: ${routeFiles.length} route group(s), ${schemaFiles.length} schema snapshot(s)`);
}
